/**
 * Таблица транслитерации кириллицы в латиницу (нижний регистр)
 */
const translitMap: Record<string, string> = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e',
    'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k',
    'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r',
    'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts',
    'ч': 'ch', 'ш': 'sh', 'щ': 'shch', 'ъ': '', 'ы': 'y',
    'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'
};

/**
 * Обратная таблица (латиница -> кириллица)
 * Ключи отсортированы по убыванию длины для корректного многобуквенного сопоставления
 */
const reverseTranslitMap: [string, string][] = [
    ['shch', 'щ'], ['sh', 'ш'], ['ch', 'ч'], ['zh', 'ж'], ['ts', 'ц'],
    ['kh', 'х'], ['yu', 'ю'], ['ya', 'я'], ['yo', 'ё'],
    ['a', 'а'], ['b', 'б'], ['v', 'в'], ['g', 'г'], ['d', 'д'],
    ['e', 'е'], ['z', 'з'], ['i', 'и'], ['y', 'ы'], ['k', 'к'],
    ['l', 'л'], ['m', 'м'], ['n', 'н'], ['o', 'о'], ['p', 'п'],
    ['r', 'р'], ['s', 'с'], ['t', 'т'], ['u', 'у'], ['f', 'ф']
];

/**
 * Преобразует русскоязычный тег в слаг для URL
 * @param tag - исходный тег (например, "Новый год 2026!")
 * @returns слаг (например, "novyy-god-2026")
 */
export function tagToSlug(tag: string): string {
    return tag
        .toLowerCase()
        .split('')
        .map(char => translitMap[char] || char) // транслитерация или оставляем как есть
        .join('')
        .replace(/[^a-z0-9\s-]/g, '')           // удаляем всё, кроме букв, цифр, пробелов и дефисов
        .trim()
        .replace(/\s+/g, '-')                   // пробелы -> дефис
        .replace(/-+/g, '-');                   // несколько дефисов подряд -> один
}

/**
 * Восстанавливает тег из слага (приближённо, с учётом неоднозначности транслитерации)
 * @param slug - слаг (например, "novyy-god-2026")
 * @returns восстановленный тег (например, "новый год 2026")
 */
export function slugToTag(slug: string): string {
    // Заменяем дефисы на пробелы (если дефис был частью слова — он потеряется)
    const result = slug.replace(/-/g, ' ');

    // Обратная транслитерация с поиском самых длинных совпадений
    let i = 0;
    let output = '';
    while (i < result.length) {
        let matched = false;
        for (const [lat, rus] of reverseTranslitMap) {
            if (result.startsWith(lat, i)) {
                output += rus;
                i += lat.length;
                matched = true;
                break;
            }
        }
        if (!matched) {
            // Если символ не найден в таблице — оставляем как есть (цифры, знаки препинания)
            output += result[i];
            i++;
        }
    }
    return output;
}